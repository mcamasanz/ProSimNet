# ============================================================
# 1. CONFIGURACIÓN
# ============================================================

Tref = 298.0
degree = 7

# ============================================================
# 2. POLINOMIOS ORIGINALES POR RANGOS
# Forma original: f(T) = a0 + a1*T + a2*T^2 + ...
# ============================================================

def poly_eval_T(T, coef):
    y = np.zeros_like(T, dtype=float)
    for i, a in enumerate(coef):
        y += a * T**i
    return y

def piecewise_function(T):
    T = np.asarray(T, dtype=float)
    y = np.zeros_like(T)

    mask_low = T <= 1000
    mask_high = T > 1000

    y[mask_low] = poly_eval_T(T[mask_low], coef_low)
    y[mask_high] = poly_eval_T(T[mask_high], coef_high)

    return y

