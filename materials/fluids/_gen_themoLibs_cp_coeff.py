plt.plot(T_data, y_fit, "--", label=f"Ajuste global grado {degree} en (T-Tref)", linewidth=2)
plt.xlabel("Temperature [K]")
plt.ylabel("Property")
plt.title("Piecewise polynomial vs global deltaT polynomial fit")
