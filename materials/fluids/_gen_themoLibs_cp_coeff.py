# ============================================================
# 3. DATOS SINTÉTICOS
# ============================================================

T_low = np.linspace(298, 1000, 400)
T_high = np.linspace(1000, 5000, 800)

T_data = np.concatenate([T_low, T_high])
y_data = piecewise_function(T_data)

# ============================================================
# 4. AJUSTE EN BASE (T - Tref)
# ============================================================

theta = T_data - Tref

# Ajuste: y = b0 + b1*theta + b2*theta^2 + ...
coef_delta_desc = np.polyfit(theta, y_data, degree)
coef_delta = coef_delta_desc[::-1]

print("\n=== Coeficientes en base (T - Tref) ===")
print("Forma: f(T) = Σ ai*(T - Tref)^i")
for i, a in enumerate(coef_delta):
    print(f"a{i} = {a:.12E}")

# Evaluar ajuste
y_fit = np.polyval(coef_delta_desc, theta)

# ============================================================
# 5. ERROR
# ============================================================

error_abs = y_fit - y_data
error_rel = 100 * error_abs / y_data

print("\n=== Errores ===")
print(f"Error absoluto máximo: {np.max(np.abs(error_abs)):.6E}")
print(f"Error relativo máximo: {np.max(np.abs(error_rel)):.6f} %")
print(f"Error relativo medio: {np.mean(np.abs(error_rel)):.6f} %")

# ============================================================
# 6. GRÁFICAS
# ============================================================

plt.figure(figsize=(8, 5))
